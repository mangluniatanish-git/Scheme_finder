// Helper: get scheme by id
export function getSchemeById(id) {
  return schemes.find(s => s.id === id || s.slug === id)
}

// Helper: get schemes by category
export function getSchemesByCategory(categoryId) {
  return schemes.filter(s => s.categories.includes(categoryId))
}

// Helper: get all central schemes
export function getCentralSchemes() {
  return schemes.filter(s => s.type === 'central')
}

// Helper: get all state schemes
export function getStateSchemes(stateCode = null) {
  const stateSchemes = schemes.filter(s => s.type === 'state')
  if (stateCode) return stateSchemes.filter(s => s.state === stateCode)
  return stateSchemes
}
